#!/usr/bin/env python3
"""Mirror the Decode Semantic engine crates from a commit of the Decode repository into engine/.

    scripts/sync-engine.py --decode <checkout> [--rev <commit>]

Copies the committed decode-semantic-core and decode-semantic crates (never uncommitted edits), writes the
workspace manifest they need and derives
engine/Cargo.lock from Decode's lock file so the mirror builds the dependency versions Decode
tests. Run it, review the diff, commit.
"""
import argparse
import io
import json
import pathlib
import re
import shutil
import subprocess
import tarfile

CRATES = ("decode-semantic-core", "decode-semantic")
root = pathlib.Path(__file__).resolve().parent.parent
engine = root / "engine"


def git(decode, *args):
    return subprocess.run(["git", "-C", str(decode), *args], check=True, capture_output=True).stdout


def workspace_dependency(manifest, name):
    """The version line of `name` in Decode's [workspace.dependencies]."""
    section = manifest.split("[workspace.dependencies]", 1)[1].split("\n[", 1)[0]
    match = re.search(rf"^{re.escape(name)}\s*=\s*(.+)$", section, re.M)
    if not match:
        raise SystemExit(f"{name} is not a workspace dependency of Decode")
    return match.group(1).strip()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--decode", required=True, type=pathlib.Path, help="Path to the Decode checkout")
    parser.add_argument("--rev", default="HEAD")
    args = parser.parse_args()
    commit = git(args.decode, "rev-parse", "--verify", f"{args.rev}^{{commit}}").decode().strip()

    workspace = f"{commit}:rust"
    paths = [f"crates/{crate}" for crate in CRATES]
    archive = git(args.decode, "archive", "--format=tar", workspace, *paths)
    for crate in CRATES:
        shutil.rmtree(engine / crate, ignore_errors=True)
    with tarfile.open(fileobj=io.BytesIO(archive)) as tar:
        for member in tar.getmembers():
            if not member.isfile():
                continue
            relative = pathlib.PurePosixPath(member.name).relative_to("crates")
            target = engine / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(tar.extractfile(member).read())

    # The crates carry the plugin release version, not Decode's.
    version = json.loads((root / "plugins/semantic-search/.claude-plugin/plugin.json").read_text())["version"]
    for crate in CRATES:
        cargo = engine / crate / "Cargo.toml"
        text = re.sub(r'^version = "[^"]*"', f'version = "{version}"', cargo.read_text(), count=1, flags=re.M)
        text = re.sub(r'(path = "\.\./decode-semantic-core", version = )"[^"]*"', rf'\g<1>"{version}"', text)
        cargo.write_text(text)

    # Every `{ workspace = true }` dependency of the crates, pinned as Decode's workspace pins it.
    manifest = git(args.decode, "show", f"{workspace}/Cargo.toml").decode()
    shared = sorted(
        {
            name
            for crate in CRATES
            for name in re.findall(r"^([\w-]+)\s*=\s*\{\s*workspace\s*=\s*true", (engine / crate / "Cargo.toml").read_text(), re.M)
        }
    )
    dependencies = "".join(f"{name} = {workspace_dependency(manifest, name)}\n" for name in shared)
    (engine / "Cargo.toml").write_text(
        "# Generated by scripts/sync-engine.py; edit the crates in Decode, not here.\n"
        "[workspace]\n"
        f"members = [{', '.join(repr(crate).replace(chr(39), chr(34)) for crate in CRATES)}]\n"
        'resolver = "3"\n\n'
        "[workspace.dependencies]\n"
        f"{dependencies}\n"
        "[profile.release]\n"
        'lto = "thin"\n'
        "codegen-units = 1\n"
        "strip = true\n"
    )
    (engine / "SOURCE").write_text('Vendored engine source in this repository\n')

    # Decode's lock, trimmed by Cargo to what the mirror uses: same versions, no other packages.
    (engine / "Cargo.lock").write_bytes(git(args.decode, "show", f"{workspace}/Cargo.lock"))
    subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--manifest-path", str(engine / "Cargo.toml")],
        check=True,
        stdout=subprocess.DEVNULL,
    )
    print("Engine source refreshed; review the diff before committing.")


if __name__ == "__main__":
    main()
